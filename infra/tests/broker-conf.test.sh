#!/usr/bin/env bash
# shellcheck disable=SC2016  # literal $( ) and backticks in test input on purpose
# Tests for infra/lib/broker-install.sh's broker.conf parser and sudoers generation, plus a check
# that every real broker under infra/brokers/ parses and yields valid sudoers.
# Touches nothing outside a temp dir. Usage: bash infra/tests/broker-conf.test.sh
set -uo pipefail
INFRA=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=../lib/broker-install.sh
. "$INFRA/lib/broker-install.sh"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
VISUDO=$(command -v visudo || { [ -x /usr/sbin/visudo ] && echo /usr/sbin/visudo; } || true)

fails=0
pass() { echo "ok   $1"; }
fail() { echo "FAIL $1"; [ -n "${2:-}" ] && sed 's/^/     /' <<< "$2"; fails=$((fails + 1)); }

# mk <name> <conf text> [reqs text]: a broker dir with a wrapper and test.sh
mk() {
  rm -rf "${T:?}/b"; mkdir -p "$T/b/$1"
  printf '%s\n' "$2" > "$T/b/$1/broker.conf"
  touch "$T/b/$1/agent-$1" "$T/b/$1/test.sh"
  [ -n "${3:-}" ] && printf '%s\n' "$3" > "$T/b/$1/requirements.txt"
  return 0
}
accepts() {  # accepts <test name> <broker name> <conf> [reqs]
  local out; mk "$2" "$3" "${4:-}"
  if broker_conf "$T/b/$2"; then pass "$1"; else fail "$1" "$B_ERR"; fi
}
rejects() {  # rejects <test name> <expected message part> <broker name> <conf> [reqs]
  local out; mk "$3" "$4" "${5:-}"
  if broker_conf "$T/b/$3"; then fail "$1 (accepted)"
  elif [[ $B_ERR == *"$2"* ]]; then pass "$1"
  else fail "$1 (wrong reason)" "$B_ERR"; fi
}
OK='USER=calbot
CALLERS="openclaw"
SECRET=caldav.env'

# ---------- accepted ----------
accepts "minimal conf" cal "$OK"
accepts "comments, blank lines, DEPS and PYREQS" cal "# a broker

$OK
  # indented comment
DEPS=\"python3-venv gh\"
PYREQS=requirements.txt" "# pinned
caldav==2.0.1 --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
lxml==6.1.3 --hash=sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa --hash=sha256:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
accepts "two callers, unquoted single values" cal 'USER=calbot
CALLERS="openclaw coder"
SECRET=caldav.env'

mk cal 'USER=calbot
CALLERS="openclaw coder"
SECRET=caldav.env'
broker_conf "$T/b/cal"
expected='# generated by claw install.sh from infra/brokers/cal/broker.conf; edit that, not this
Defaults!/usr/local/bin/agent-cal env_reset, !setenv
openclaw ALL=(calbot) NOPASSWD: /usr/local/bin/agent-cal
coder ALL=(calbot) NOPASSWD: /usr/local/bin/agent-cal'
got=$(broker_sudoers)
[ "$got" = "$expected" ] && pass "sudoers: env_reset, !setenv and one line per caller" || fail "sudoers text" "$got"

# ---------- rejected: nothing in broker.conf is ever executed ----------
rejects "command substitution" "bad line" cal "USER=x\$(touch $T/pwned)
CALLERS=openclaw
SECRET=s"
rejects "backticks" "bad line" cal "$OK
DEPS=\"\`touch $T/pwned\`\""
rejects "semicolon" "bad line" cal "$OK
DEPS=gh;touch"
rejects "single quotes" "bad line" cal "USER='calbot'
CALLERS=openclaw
SECRET=s"
rejects "spaces around =" "bad line" cal "USER = calbot"
rejects "lowercase key" "bad line" cal "user=calbot"
rejects "CRLF line endings" "bad line" cal "$(printf 'USER=calbot\r\nCALLERS=openclaw\r\nSECRET=s\r')"
[ ! -e "$T/pwned" ] && pass "no injected command ran" || fail "an injected command ran"

rejects "unknown key" "unknown key SHELL" cal "$OK
SHELL=bash"
rejects "key set twice" "USER set twice" cal "$OK
USER=other"
rejects "missing USER" "USER" cal 'CALLERS=openclaw
SECRET=s'
for u in root openclaw coder; do
  rejects "reserved USER $u" "can't be $u" cal "USER=$u
CALLERS=openclaw
SECRET=s"
done
# the admin running sudo claw-install is reserved too, by $SUDO_USER rather than by name
export SUDO_USER="admin"
# shellcheck source=../lib/broker-install.sh
. "$INFRA/lib/broker-install.sh"
rejects "reserved USER: the sudo caller" "can't be admin" cal 'USER=admin
CALLERS=openclaw
SECRET=s'
unset SUDO_USER
# shellcheck source=../lib/broker-install.sh
. "$INFRA/lib/broker-install.sh"
accepts "no SUDO_USER: nothing extra reserved" cal 'USER=admin
CALLERS=openclaw
SECRET=s'
rejects "USER with uppercase" "bad or missing USER" cal 'USER=CalBot
CALLERS=openclaw
SECRET=s'
rejects "USER too long" "bad or missing USER" cal "USER=$(printf 'a%.0s' {1..33})
CALLERS=openclaw
SECRET=s"
rejects "missing CALLERS" "CALLERS missing" cal 'USER=calbot
SECRET=s'
for c in admin root ALL gitbot "%sudo"; do
  rejects "caller not allowlisted: $c" "" cal "USER=calbot
CALLERS=\"$c\"
SECRET=s"
done
rejects "caller listed twice" "listed twice" cal 'USER=calbot
CALLERS="openclaw openclaw"
SECRET=s'
rejects "missing SECRET" "SECRET" cal 'USER=calbot
CALLERS=openclaw'
for s in ../x .hidden "a b"; do
  rejects "SECRET not a plain file name: $s" "" cal "USER=calbot
CALLERS=openclaw
SECRET=\"$s\""
done
rejects "SECRET with a slash" "bad line" cal 'USER=calbot
CALLERS=openclaw
SECRET=a/b'
rejects "bad apt package" "bad apt package" cal "$OK
DEPS=\"gh -y\""
rejects "PYREQS file missing" "PYREQS must name a file" cal "$OK
PYREQS=nope.txt"
rejects "PYREQS pinned but no hash" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav==2.0.1"
rejects "PYREQS short hash" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav==2.0.1 --hash=sha256:abc"
rejects "PYREQS md5 hash" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav==2.0.1 --hash=md5:0123456789abcdef0123456789abcdef"
rejects "PYREQS with >=" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav>=2"
rejects "PYREQS unpinned" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav"
rejects "PYREQS with pip options" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "--index-url=https://evil.example/simple"
rejects "PYREQS with a URL" "name==version --hash" cal "$OK
PYREQS=requirements.txt" "caldav @ https://evil.example/caldav.whl"
rejects "bad broker dir name" "bad broker name" Cal "$OK"
rejects "underscore in broker name" "bad broker name" my_cal "$OK"
mk cal "$OK"; rm "$T/b/cal/agent-cal"
broker_conf "$T/b/cal" && fail "missing wrapper accepted" || { [[ $B_ERR == *"no wrapper"* ]] && pass "missing wrapper rejected" || fail "missing wrapper" "$B_ERR"; }
mk cal "$OK"; rm "$T/b/cal/test.sh"
broker_conf "$T/b/cal" && fail "missing test.sh accepted" || { [[ $B_ERR == *"no test.sh"* ]] && pass "missing test.sh rejected" || fail "missing test.sh" "$B_ERR"; }

# ---------- checks across brokers ----------
mkb() {  # mkb <name> <user>: a broker dir under $T/multi
  mkdir -p "$T/multi/$1"; touch "$T/multi/$1/agent-$1" "$T/multi/$1/test.sh"
  printf 'USER=%s\nCALLERS=openclaw\nSECRET=s\n' "$2" > "$T/multi/$1/broker.conf"
}
mkb cal calbot; mkb git gitbot
brokers_check "$T/multi"/*/ && pass "brokers with distinct users pass" || fail "distinct users" "$B_ERR"
mkb evil gitbot
if brokers_check "$T/multi"/*/; then fail "two brokers sharing USER accepted"
elif [[ $B_ERR == *"USER gitbot is already used by another broker"* ]]; then pass "two brokers sharing a USER rejected"
else fail "shared USER (wrong reason)" "$B_ERR"; fi
rm -rf "$T/multi"
brokers_check "$INFRA"/brokers/*/ && pass "real brokers pass brokers_check" || fail "real brokers fail brokers_check" "$B_ERR"

# ---------- the real brokers ----------
n=0
for b in "$INFRA"/brokers/*/; do
  n=$((n + 1)); name=$(basename "$b")
  if ! broker_conf "$b"; then fail "brokers/$name/broker.conf parses" "$B_ERR"; continue; fi
  pass "brokers/$name/broker.conf parses"
  broker_sudoers > "$T/sudoers"
  if [ -n "$VISUDO" ]; then
    if out=$("$VISUDO" -cf "$T/sudoers" 2>&1); then pass "brokers/$name sudoers passes visudo"; else fail "brokers/$name sudoers passes visudo" "$out"; fi
  fi
done
[ "$n" -gt 0 ] && pass "found $n real broker(s)" || fail "no brokers found under infra/brokers"

if broker_conf "$INFRA/brokers/git"; then
  expected='# generated by claw install.sh from infra/brokers/git/broker.conf; edit that, not this
Defaults!/usr/local/bin/agent-git env_reset, !setenv
openclaw ALL=(gitbot) NOPASSWD: /usr/local/bin/agent-git
coder ALL=(gitbot) NOPASSWD: /usr/local/bin/agent-git'
  got=$(broker_sudoers)
  [ "$got" = "$expected" ] && pass "git broker: same sudo rules as the old agent-git.sudoers + coder.sudoers line" || fail "git broker sudoers" "$got"
fi
[ -z "$VISUDO" ] && echo "skip visudo checks (visudo not installed)"

echo; [ $fails = 0 ] && echo "all broker-conf tests passed" || { echo "$fails failed"; exit 1; }
